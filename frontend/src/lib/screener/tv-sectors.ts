// zzz948 — TradingView's 21 sectors, worked out for our rows. TradingView files every company under one of 21 sectors (FactSet's
// scheme); our rows carry the Nasdaq sector + industry (USA) or the screener.in sector + industry (India). The tables below were
// learnt once from real companies: every company in our snapshots was looked up in TradingView and each of our industries is mapped
// to the TradingView sector most of its companies have. The app itself never calls TradingView.
//
// Honest limits: an industry does not always sit in one TradingView sector (Nasdaq's "Finance: Consumer Services" holds banks AND
// payment-software companies; TradingView splits them). Measured on 7 Oct 2026: the mapping gives TradingView's sector for about 79%
// of US companies and 80% of Indian ones (a sample of 500). An industry not seen when the table was made falls back to its sector's most common
// TradingView sector; no sector at all → unknown (a sector filter then fails for that company, as TradingView's does for unknowns).

export const TV_SECTORS = [
  'Commercial Services', 'Communications', 'Consumer Durables', 'Consumer Non-Durables', 'Consumer Services', 'Distribution Services',
  'Electronic Technology', 'Energy Minerals', 'Finance', 'Government', 'Health Services', 'Health Technology', 'Industrial Services',
  'Miscellaneous', 'Non-Energy Minerals', 'Process Industries', 'Producer Manufacturing', 'Retail Trade', 'Technology Services',
  'Transportation', 'Utilities',
] as const;
export type TvSector = (typeof TV_SECTORS)[number];

/** All 21 sectors except the ones named (how most of the owner's screens are written). */
export const allSectorsExcept = (...not: TvSector[]): TvSector[] => TV_SECTORS.filter((s) => !not.includes(s));

/** The TradingView sector for a row's own sector + industry, or null when it cannot be told. */
export function tvSectorOf(market: 'US' | 'IN', sec: string | null | undefined, ind: string | null | undefined): TvSector | null {
  const byInd = market === 'US' ? US_BY_INDUSTRY : IN_BY_INDUSTRY;
  const bySec = market === 'US' ? US_BY_SECTOR : IN_BY_SECTOR;
  const s = (sec || '').trim(), i = (ind || '').trim();
  let k: number | undefined;
  if (i) k = byInd[`${s}|${i}`];
  if (k == null && i) { const hit = Object.keys(byInd).find((x) => x.slice(x.indexOf('|') + 1) === i); if (hit) k = byInd[hit]; }
  if (k == null && s) k = bySec[s];
  return k == null ? null : TV_SECTORS[k];
}

