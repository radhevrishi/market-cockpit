async function fetchFmpEarningsCalendar(daysAhead: number): Promise<Array<{
  date: string;
  type: 'earnings';
  region: 'US';
  title: string;
  ticker: string;
  importance: 'high' | 'medium';
}>> {
  if (!FMP_KEY) return [];
  const fromDate = istDateIso();
  const toDate = addDaysIso(fromDate, daysAhead);
  try {
    const r = await fetch(
      `${STABLE}/earnings-calendar?from=${fromDate}&to=${toDate}&apikey=${FMP_KEY}`,
      { signal: AbortSignal.timeout(8000), next: { revalidate: 3600 } },
    );
    if (!r.ok) return [];
    const arr = await r.json();
    if (!Array.isArray(arr)) return [];
    // Filter to high-cap names + names with non-null EPS estimate (likely
    // covered enough to matter). Cap at 60 to keep response small.
    return arr
      .filter((e: any) => e.epsEstimated != null || e.revenueEstimated != null)
      .slice(0, 60)
      .map((e: any) => ({
        date: e.date,
        type: 'earnings' as const,
        region: 'US' as const,
        title: `${e.symbol} earnings (cons EPS ${e.epsEstimated ?? '—'}, rev ${e.revenueEstimated != null ? '$' + Math.round(e.revenueEstimated / 1e6) + 'M' : '—'})`,
        ticker: e.symbol,
        importance: 'high' as const,
      }));
  } catch {
    return [];
  }
}

/** zzz897 — India results board meetings for the coming days, from the daily refresh-earnings-calendar cron keys. */
async function fetchIndiaBoardMeetings(fromIso: string, toIso: string): Promise<Record<string, string[]>> {
  if (!isRedisAvailable()) return {};
  const days = daysBetween(fromIso, toIso, 62);
  try {
    const rows = await kvMGet<string[]>(days.map((d) => `earnings-cal:auto:${d}`));
    const out: Record<string, string[]> = {};
    days.forEach((d, i) => { const r = rows[i]; if (Array.isArray(r) && r.length) out[d] = r; });
    return out;
  } catch { return {}; }
}

export async function GET(request: Request) {
  try {
    // zzz897 — `?days=` is honoured (callers ask for 7 or 14; it was ignored), dates are the IST day, and India
    // companies are included (the endpoint used to carry only US FMP earnings + a 2026-only macro list, so the
    // home "next 7 days" panel and the Auto-Val "earnings in N days" chip never saw an Indian company from it).
    const url = new URL(request.url);
    const daysParam = parseInt(url.searchParams.get('days') || '', 10);
    const horizonDays = Number.isFinite(daysParam) ? Math.min(60, Math.max(1, daysParam)) : 30;
    const todayStr = istDateIso();
    const tomorrow = addDaysIso(todayStr, 1);
    const week = addDaysIso(todayStr, Math.min(7, horizonDays));
    const month = addDaysIso(todayStr, horizonDays);

    const [fmpEarnings, indiaByDate] = await Promise.all([
      fetchFmpEarningsCalendar(horizonDays),
      fetchIndiaBoardMeetings(todayStr, month),
      warmNseHolidays(), // zzz905: macro-event dates skip holidays of every year, not only 2026
    ]);

    const all: Array<any> = [
      ...CALENDAR_STATIC.filter(e => e.date >= todayStr && e.date <= month),
      ...recurringIndiaMacroEvents(todayStr, month, nseHolidaySet()),
      ...fmpEarnings,
    ];

    all.sort((a, b) => a.date.localeCompare(b.date));

    const buckets = {
      tomorrow: all.filter(e => e.date <= tomorrow),
      this_week: all.filter(e => e.date > tomorrow && e.date <= week),
      this_month: all.filter(e => e.date > week && e.date <= month),
    };

    // Company events by date (India board meetings + US earnings) — the shape the home page's flattenCalendar reads.
    type CompanyEvent = { symbol: string; ticker: string; date: string; region: 'IN' | 'US'; type: 'earnings' };
    const by_date: Record<string, CompanyEvent[]> = {};
    let indiaCount = 0;
    for (const [d, list] of Object.entries(indiaByDate)) {
      by_date[d] = list.map((t) => ({ symbol: t, ticker: t, date: d, region: 'IN' as const, type: 'earnings' as const }));
      indiaCount += list.length;
    }
    for (const e of fmpEarnings) {
      if (!e.date || e.date < todayStr || e.date > month) continue;
      if (!by_date[e.date]) by_date[e.date] = [];
      by_date[e.date].push({ symbol: e.ticker, ticker: e.ticker, date: e.date, region: 'US', type: 'earnings' });
    }
    const staticThrough = CALENDAR_STATIC.reduce((mx, e) => (e.date > mx ? e.date : mx), '');

    return NextResponse.json({
      ok: true,
      generated_at: new Date().toISOString(),
      today: todayStr,
      horizon_days: horizonDays,
      counts: {
        tomorrow: buckets.tomorrow.length,
        this_week: buckets.this_week.length,
        this_month: buckets.this_month.length,
        total: all.length,
        india_earnings: indiaCount,
        us_earnings: fmpEarnings.length,
      },
      buckets,
      by_date,
      static_through: staticThrough || null,
      static_stale: !staticThrough || staticThrough < todayStr,
    });
  } catch (err: any) {
    return NextResponse.json(
      { ok: false, error: err?.message || 'calendar_fetch_error', buckets: { tomorrow: [], this_week: [], this_month: [] }, by_date: {} },
      { status: 200 },
    );
  }
}
